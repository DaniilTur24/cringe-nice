export const SPECIAL_ROLES = ['prosecutor', 'judge', 'ghost', 'oligarch', 'detective']

export function rolePerks(roleMetadata = {}) {
  const role = roleMetadata.role ?? 'civilian'
  if (role === 'prosecutor') {
    const limit = roleMetadata.double_vote_limit ?? 3
    const used = roleMetadata.double_vote_count ?? 0
    return [
      `Удваиваешь вес своего голоса ${Math.max(limit - used, 0)}/${limit} раз за день.`,
      'Работает только на голоса “за” с ненулевым баллом.',
      'После дневного реролла заряды обновляются.',
    ]
  }
  if (role === 'judge') {
    return [
      `Можешь двигать слайдер до ±20, осталось ${roleMetadata.super_verdict_remaining ?? 0}/2 супер-вердикта.`,
      'Заряд тратится только если дело реально одобрено.',
      'Твой голос может резко изменить итоговый балл.',
    ]
  }
  if (role === 'ghost') {
    return [
      'Твои жалобы остаются анонимными даже при отклонении.',
      'Жалобы Призрака не попадают в архив дел.',
      'Призрака нельзя раскрыть Детективом.',
    ]
  }
  if (role === 'oligarch') {
    const limit = roleMetadata.reward_limit ?? 3
    const pct = roleMetadata.cashback_pct ?? 25
    const used = Math.min(roleMetadata.reward_create_count ?? 0, limit)
    const hidden = roleMetadata.pending_cashback ?? 0
    return [
      `Получаешь ${pct}% скрытого кэшбэка с первых одобренных наград: ${used}/${limit} использовано.`,
      `Сейчас скрыто накоплено: ${hidden} баллов.`,
      'В конце дня кэшбэк раскрывается и падает в общий счёт.',
    ]
  }
  if (role === 'detective') {
    const limit = roleMetadata.reveals_limit ?? 2
    return [
      `Можешь узнать автора закрытой одобренной жалобы: ${roleMetadata.reveals_remaining ?? 0}/${limit} зарядов.`,
      'Сначала раскрываешь автора только себе.',
      'Потом можешь бесплатно раскрыть уже известного автора всем.',
    ]
  }
  return [
    'Нет скрытой суперсилы, зато нет и подозрений.',
    'Голосуй честно, подавай иски и награды.',
    'Завтра рулетка может дать роль пожирнее.',
  ]
}

